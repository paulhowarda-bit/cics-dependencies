def _render(header: str, statements) -> str:
    lines = [header.rstrip("\n")]
    for label, operation, operands in statements:
        if not operands:
            lines.append("{0:<9}{1}".format(label, operation).rstrip())
            continue
        lines.extend(statement(label, operation, operands))
    return "\n".join(lines) + "\n"


GENERATED = {
    "legacy.pct": lambda: _render(_LEGACY_PCT_HEADER, _LEGACY_PCT),
    "lgmap.bms": lambda: _render(_BMS_HEADER, _LGMAP_BMS),
}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="fail if a committed example has drifted from the generator")
    args = parser.parse_args(argv)

    drifted = []
    for name, build in sorted(GENERATED.items()):
        path = EXAMPLES / name
        text = build()
        if args.check:
            current = path.read_text(encoding="utf-8") if path.is_file() else None
            if current != text:
                drifted.append(name)
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print("wrote %s (%d lines)" % (path, text.count("\n")))

    if args.check:
        if drifted:
            print("GENERATED EXAMPLES HAVE DRIFTED: %s" % ", ".join(drifted))
            print("\n  python tools/make_examples.py")
            return 1
        print("generated examples match: %s" % ", ".join(sorted(GENERATED)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
