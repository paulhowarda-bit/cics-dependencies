#!/usr/bin/env python3
"""Generate the COLUMN-SENSITIVE examples, rather than hand-spacing them.

The CSD decks in ``examples/`` are free-form and are written by hand. The macro table deck
is not: HLASM continues a statement only when column 72 - column 72 exactly - is non-blank,
and a mark that lands in column 74 continues nothing. That failure is silent. The statement
ends, the next line is read as a fresh one, its operation is not a known macro, and every
operand on it disappears without a word.

This repository's own first draft of ``legacy.pct`` had exactly that bug, which is why the
deck is generated and why ``test_examples.py`` fails if the committed file drifts from what
this produces. Fixtures for a column language are worthless if the columns are approximate,
and hand-spacing does not survive editing.

    python tools/make_examples.py            # rewrite the generated examples
    python tools/make_examples.py --check    # fail if the committed files have drifted
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path
from typing import List, Sequence

REPO = Path(__file__).resolve().parents[1]
EXAMPLES = REPO / "examples"

CONTINUE_COLUMN = 72        # 1-based: the mark goes here and nowhere else
RESUME_COLUMN = 16          # 1-based: a continuation's operands resume here


def statement(label: str, operation: str, operands: Sequence[str]) -> List[str]:
    """One macro statement, continued at column 72 and resumed at column 16.

    Operands are packed greedily, and the continuation mark is placed by measurement
    rather than by counting spaces in a text editor.
    """
    head = "{0:<9}{1} ".format(label, operation)
    lines: List[str] = []
    current = head
    for index, operand in enumerate(operands):
        piece = operand + ("," if index < len(operands) - 1 else "")
        if len(current) + len(piece) > CONTINUE_COLUMN - 1:
            lines.append(current.rstrip().ljust(CONTINUE_COLUMN - 1) + "X")
            current = " " * (RESUME_COLUMN - 1)
        current += piece
    lines.append(current.rstrip())
    return lines


